const assert = require("node:assert/strict");
const { chromium } = require(process.env.PLAYWRIGHT_MODULE || "playwright");
(async () => {
  let input = "";
  for await (const chunk of process.stdin) input += chunk;
  const { base, token } = JSON.parse(input);
  const browser = await chromium.launch({ headless: true, ...(process.env.BROWSER_EXECUTABLE ? { executablePath: process.env.BROWSER_EXECUTABLE } : {}) });
  try {
    const context = await browser.newContext({ viewport: { width: 1440, height: 1000 } });
    const page = await context.newPage();
    const errors = [];
    page.on("pageerror", e => errors.push(e.message));
    page.on("console", msg => { if (msg.type() === "error") errors.push(msg.text()); });
    await page.goto(base);
    await page.waitForFunction(() => document.querySelector("#entry-count").textContent !== "—");
    const stats = await (await context.request.get(base + "/stats")).json();
    assert(stats.total_entries > 0);
    assert(stats.examples.length > 0);
    await page.fill("#query", stats.examples[0]);
    await page.click("#search-button");
    await page.waitForSelector("#results .entry");
    assert.match(await page.locator("#results").innerText(), /Imported \u00b7 unverified|Dictionary source/);
    assert.match(await page.locator("#results").innerText(), /Confidence: not established/);
    assert.match(await page.locator("#results").innerText(), /Sources:/);
    const title = await page.locator("#results .entry h3").first().innerText();
    const translation = await page.locator("#results .translation").first().innerText();
    await page.waitForSelector("#headword-list button");
    const firstHeadword = await page.locator("#headword-list button").first().innerText();
    await page.locator("#headword-list button").first().click();
    await page.waitForSelector("#word-detail .dictionary-sense");
    assert.equal(await page.locator("#word-detail h3").innerText(), firstHeadword);
    assert.match(await page.locator("#word-detail a").first().getAttribute("href"), /headword=/);
    await page.waitForFunction(() => document.querySelector("#coverage-status").textContent.includes("without sourced examples"));
    await page.fill("#headword-prefix", "%");
    await page.locator("#index-form button").click();
    await page.waitForFunction(() => document.querySelector("#index-status").textContent.startsWith("0 of 0"));
    // Correcting an actual corpus record must open a prefilled form.
    await page.locator("#results .entry button").first().click();
    assert.equal(await page.inputValue("#english"), title);
    assert.equal(await page.inputValue("#yoruba"), translation);
    await page.fill("#english", "Ede browser test record");
    await page.fill("#yoruba", "Synthetic test text — not verified");
    await page.fill("#username", "<img src=x onerror=alert(1)>");
    await page.fill("#dialect", "test dialect");
    await page.check('input[name="consent"]');
    await page.click("#submit-contribution");
    await page.waitForFunction(() => document.querySelector("#contribution-status").textContent.includes("Reference:"));
    assert.match(await page.locator("#contribution-status").innerText(), /Saved for review/);
    await page.selectOption("#record-kind", "all");
    await page.fill("#query", "Ede browser test record");
    await page.click("#search-button");
    await page.waitForFunction(() => document.querySelector("#search-status").textContent.includes("No matching record"));
    assert.equal(await page.locator("#results .entry").count(), 0);
    await page.locator("#editor summary").click();
    await page.fill("#review-token", token);
    await page.locator("#review-form button").click();
    await page.waitForSelector("#review-queue .entry");
    assert.match(await page.locator("#review-queue").innerText(), /<img src=x onerror=alert\(1\)>/);
    assert.equal(await page.locator("#review-queue img").count(), 0);
    await page.getByRole("button", { name: "Approve as editor-reviewed" }).click();
    await page.waitForFunction(() => document.querySelector("#review-status").textContent.includes("0 community suggestions"));
    await page.fill("#query", "Ede browser test record");
    await page.click("#search-button");
    await page.waitForSelector("#results .entry");
    assert.match(await page.locator("#results").innerText(), /Editor reviewed/);
    assert.match(await page.locator("#results").innerText(), /Native-speaker verification: not established/);
    if (stats.dictionary_senses > 0) {
      await page.getByRole("button", { name: "Mark this sense reviewed" }).first().click();
      await page.waitForFunction(() => document.querySelector("#reviewed-count").textContent === "1");
      const afterReview = await (await context.request.get(base + "/stats")).json();
      assert.equal(afterReview.reviewed_senses, 1);
      assert.equal(afterReview.native_speaker_verified, 0);
    }
    // A server failure must not clear the user's unsaved text or claim success.
    await page.fill("#english", "Unsaved browser example");
    await page.fill("#yoruba", "Retained text");
    await page.check('input[name="consent"]');
    await page.route("**/contribute", route => route.fulfill({ status: 503, contentType: "application/json", body: JSON.stringify({ detail: "Test storage failure" }) }));
    await page.click("#submit-contribution");
    await page.waitForFunction(() => document.querySelector("#contribution-status").textContent.includes("Test storage failure"));
    assert.equal(await page.inputValue("#yoruba"), "Retained text");
    await page.unroute("**/contribute");
    // Dedicated portal: propose and approve a meaning-specific synonym in the isolated DB.
    await page.goto(base + "/review");
    await page.fill("#access-key", token);
    await page.locator("#portal-login button").click();
    await page.waitForSelector("#workspace:not([hidden])");
    await page.selectOption("#queue-type", "senses");
    await page.waitForSelector("#portal-queue .dictionary-sense");
    const pendingSense = await (await context.request.get(base + "/review/senses?limit=1", { headers: { Authorization: "Bearer " + token } })).json();
    const wordForSynonym = pendingSense.senses[0].yoruba;
    const proposal = page.locator("#portal-queue article").first().locator("details");
    await proposal.locator("summary").click();
    await proposal.getByLabel("Yoruba synonym, with tone marks").fill("fixture-synonym");
    await proposal.getByLabel("Evidence or source reference").fill("Synthetic browser fixture, not dictionary evidence");
    await proposal.getByLabel("Usage, dialect and context").fill("Test relationship only");
    await proposal.getByRole("button", { name: "Save synonym proposal" }).click();
    await page.waitForFunction(() => document.querySelector("#portal-status").textContent.includes("Synonym saved for review"));
    let lookup = await (await context.request.get(base + "/dictionary/word?" + new URLSearchParams({ headword: wordForSynonym }))).json();
    assert(!lookup.senses.flatMap(s => s.synonyms).some(s => s.word === "fixture-synonym"));
    await page.selectOption("#queue-type", "synonyms");
    await page.fill("#queue-query", "fixture-synonym");
    await page.locator("#queue-controls button").click();
    await page.waitForSelector("#portal-queue article");
    await page.getByLabel("Review note (optional)").fill("Checked in browser fixture");
    await page.getByRole("button", { name: "Approve synonym", exact: true }).click();
    await page.waitForFunction(() => document.querySelector("#batch-status").textContent === "No records in this batch.");
    lookup = await (await context.request.get(base + "/dictionary/word?" + new URLSearchParams({ headword: wordForSynonym }))).json();
    assert(lookup.senses.flatMap(s => s.synonyms).some(s => s.word === "fixture-synonym"));
    const dictionaryPage = await context.newPage();
    await dictionaryPage.goto(base + "/?" + new URLSearchParams({ headword: wordForSynonym }));
    await dictionaryPage.waitForSelector("#word-detail .dictionary-sense");
    assert.match(await dictionaryPage.locator("#word-detail").innerText(), /Synonyms for this meaning/);
    assert.match(await dictionaryPage.locator("#word-detail").innerText(), /fixture-synonym/);
    await dictionaryPage.close();
    await page.selectOption("#queue-type", "approved-synonyms");
    await page.waitForSelector("#portal-queue article");
    await page.getByLabel("Review note (optional)").fill("Withdraw test relationship");
    await page.getByRole("button", { name: "Withdraw synonym", exact: true }).click();
    await page.waitForFunction(() => document.querySelector("#batch-status").textContent === "No records in this batch.");
    lookup = await (await context.request.get(base + "/dictionary/word?" + new URLSearchParams({ headword: wordForSynonym }))).json();
    assert(!lookup.senses.flatMap(s => s.synonyms).some(s => s.word === "fixture-synonym"));
    await page.selectOption("#queue-type", "history");
    await page.waitForSelector("#portal-queue article");
    assert.match(await page.locator("#portal-queue").innerText(), /Checked in browser fixture/);
    assert.equal(await page.evaluate(() => localStorage.length + sessionStorage.length), 0);
    await page.getByRole("button", { name: "Sign out", exact: true }).click();
    assert.equal(await page.locator("#portal-queue article").count(), 0);
    assert(await page.locator("#workspace").isHidden());
    // Ignore the expected simulated 503 browser console message.
    const unexpected = errors.filter(e => !e.includes("503") && !e.includes("favicon.ico") && !e.includes("404"));
    assert.deepEqual(unexpected, []);
    await page.setViewportSize({ width: 390, height: 844 });
    await page.goto(base);
    await page.waitForFunction(() => document.querySelector("#entry-count").textContent !== "—");
    assert(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth));
    await page.goto(base + "/review");
    assert(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth));
    console.log(JSON.stringify({ reviewerPortal: true, synonymApprovalAndWithdrawal: true, status: "passed", realCorpusPairs: stats.total_entries, search: true, contribution: true, review: true, failedSave: true, mobile: true }));
    await context.close();
  } finally { await browser.close(); }
})().catch(error => { console.error(error.message); process.exitCode = 1; });
